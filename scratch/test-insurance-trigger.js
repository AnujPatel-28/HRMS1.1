import { createClient } from "@insforge/sdk";

const baseUrl = process.env.VITE_INSFORGE_URL || "https://rq3qmu8y-jx7.ap-southeast.insforge.app";
const anonKey = process.env.VITE_INSFORGE_ANON_KEY || "ik_48f0f767d6c40717ba3112c9dca15a3b";
const tenantId = "97da3641-d69e-4e7a-bdc9-760675be8d28";
const empId = "24ef7b09-f9c4-4a66-88e4-7e0f046ad62d"; // Anuj Patel (active employee)

if (!baseUrl || !anonKey) {
  console.error("Missing env");
  process.exit(1);
}

const client = createClient({ baseUrl, anonKey });

async function run() {
  console.log("1. Creating dummy expiring policy...");
  
  const today = new Date();
  const fifteenDaysLater = new Date(today.getTime() + 15 * 24 * 60 * 60 * 1000);
  const startStr = today.toISOString().slice(0, 10);
  const expiryStr = fifteenDaysLater.toISOString().slice(0, 10);

  const { data: policy, error: createError } = await client.database
    .from("insurance_policies")
    .insert([{
      tenant_id: tenantId,
      employee_id: empId,
      insurer_name: "Test Insurer Corp",
      policy_number: "TEST-CRON-12345",
      policy_type: "Health",
      coverage_amount: 500000,
      premium_amount: 12000,
      premium_frequency: "Annual",
      start_date: startStr,
      expiry_date: expiryStr,
      status: "Active",
      rm_name: "RM John",
      rm_phone: "9876543210",
      rm_email: "rm@test.com",
      rm_company: "Test Insurer Corp"
    }])
    .select()
    .single();

  if (createError) {
    console.error("Create Policy Error:", createError);
    return;
  }

  console.log("Dummy policy created successfully! ID:", policy.id);

  console.log("2. Triggering Deno edge function via HTTP POST...");
  try {
    const res = await fetch("https://rq3qmu8y.functions.insforge.app/insurance-expiry-check", {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({ date: startStr })
    });

    console.log("Deno trigger HTTP status:", res.status);
    const result = await res.json();
    console.log("Deno response:", result);

    console.log("3. Fetching notifications generated by the cron job...");
    const { data: notifications, error: notifError } = await client.database
      .from("notifications")
      .select("*")
      .eq("tenant_id", tenantId)
      .eq("type", "general")
      .in("title", ["Insurance Expiring Soon", "Employee Insurance Expiring"]);

    if (notifError) {
      console.error("Notifications fetch error:", notifError);
    } else {
      console.log(`Found ${notifications.length} notifications of type 'general' and insurance titles:`);
      notifications.forEach(n => {
        console.log(`- To: ${n.employee_id} | Title: "${n.title}" | Body: "${n.body}"`);
      });
    }

  } catch (err) {
    console.error("Error triggering function:", err);
  } finally {
    console.log("4. Cleaning up (deleting test policy and notifications)...");
    
    // Delete policy
    const { error: delPolicyError } = await client.database
      .from("insurance_policies")
      .delete()
      .eq("id", policy.id);

    if (delPolicyError) console.error("Error deleting policy:", delPolicyError);
    else console.log("Test policy deleted successfully!");

    // Delete notifications
    const { data: listToDelete } = await client.database
      .from("notifications")
      .select("id")
      .eq("tenant_id", tenantId)
      .eq("type", "general")
      .in("title", ["Insurance Expiring Soon", "Employee Insurance Expiring"]);

    if (listToDelete && listToDelete.length > 0) {
      for (const notif of listToDelete) {
        await client.database.from("notifications").delete().eq("id", notif.id);
      }
      console.log("Test notifications deleted successfully!");
    }
  }
}

run().catch(console.error);
